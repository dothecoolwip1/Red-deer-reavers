// Writes the public HTML pages from scripts/pages/*.page.mjs so the header, footer and mobile dock stay identical everywhere.
// Edit the page sources, then run `npm run pages`. The generated HTML is committed because GitHub Pages serves the repository root.
import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const dir = path.join(process.cwd(), "scripts", "pages");
const sources = (await fs.readdir(dir)).filter(name => name.endsWith(".page.mjs")).sort();
for (const name of sources) {
  const mod = await import(pathToFileURL(path.join(dir, name)).href);
  const html = mod.default().replace(/^<!doctype html>\n/i, "<!doctype html>\n<!-- Generated by scripts/build-pages.mjs from scripts/pages/" + name + ". Edit that file and run npm run pages. -->\n");
  await fs.writeFile(path.join(process.cwd(), mod.file), html);
  console.log(`wrote ${mod.file}`);
}
